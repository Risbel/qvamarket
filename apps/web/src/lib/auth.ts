import { betterAuth } from "better-auth";
import { drizzleAdapter } from "@better-auth/drizzle-adapter";
import { nextCookies } from "better-auth/next-js";
import { admin, organization } from "better-auth/plugins";
import { db } from "@qvashop/db";

export const auth = betterAuth({
  database: drizzleAdapter(db, { provider: "pg" }),
  emailAndPassword: { enabled: true },
  user: {
    additionalFields: {
      // Set by the superadmin when creating a merchant with a temporary password.
      // input: false -> users cannot set it themselves; it is cleared server-side.
      mustChangePassword: { type: "boolean", defaultValue: false, input: false },
    },
  },
  advanced: {
    // UUID primary keys (generated by PostgreSQL), per project convention
    database: { generateId: "uuid" },
  },
  plugins: [
    admin(),
    organization(), // a company (tenant) is an organization; its stores reference organization.id
    nextCookies(), // must be the last plugin
  ],
});
